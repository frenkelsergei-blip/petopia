"""Build size-limited runtime copies of source images from measured display scale.

Reads test-results/texture-scale/report.json (tools/measure_texture_scale.py),
writes assets/runtime/<source path>.png plus assets/runtime/manifest.json, and
switches the Web export list from each source image to its runtime copy.
Source images stay untouched and remain the art of record.
"""
import json, math, re
from pathlib import Path
from PIL import Image
ROOT = Path(__file__).resolve().parents[1]
RUNTIME = ROOT / 'assets/runtime'
MARGIN = 1.15      # headroom over the largest measured on-screen size
MIN_SIDE = 64
MIN_SAVING = 0.25  # keep the source when a copy would save less than this

IMPORT = '[remap]\n\nimporter="image"\ntype="Image"\n'

def runtime_path(source):
    return 'res://assets/runtime/' + source[len('res://assets/'):]

def build(report):
    plan = {}
    for source, item in sorted(report.items()):
        if item['needed'] is None: continue  # never seen on a captured screen: keep the source
        w, h = item['source']
        scale = min(1.0, item['needed'] * MARGIN)
        size = (max(min(w, MIN_SIDE), math.ceil(w * scale)), max(min(h, MIN_SIDE), math.ceil(h * scale)))
        if size[0] * size[1] > (1 - MIN_SAVING) * w * h: continue
        image = Image.open(ROOT / source[6:]).convert('RGBA')
        # Premultiplied resampling keeps transparent edges from darkening.
        small = image.convert('RGBa').resize(size, Image.LANCZOS).convert('RGBA')
        target = ROOT / runtime_path(source)[6:]
        target.parent.mkdir(parents=True, exist_ok=True)
        small.save(target, optimize=True)
        imported = Path(str(target) + '.import')
        if not imported.exists() or 'importer="image"' not in imported.read_text(): imported.write_text(IMPORT)
        plan[source] = {'runtime': runtime_path(source), 'source': [w, h], 'runtime_size': list(size), 'measured_scale': item['needed'], 'measured_on': item['shot']}
    return plan

def update_exports(plan):
    preset = ROOT / 'export_presets.cfg'
    text = preset.read_text()
    match = re.search(r'export_files=PackedStringArray\((.*?)\)\n', text)
    files = re.findall(r'"([^"]+)"', match.group(1))
    originals = {v['runtime']: k for k, v in json.loads((RUNTIME / 'manifest.json').read_text())['textures'].items()} if (RUNTIME / 'manifest.json').exists() else {}
    files = [originals.get(f, f) for f in files]  # start from source paths
    files = sorted({plan[f]['runtime'] if f in plan else f for f in files} | {'res://scripts/art/art_texture.gd', 'res://assets/runtime/manifest.json'})
    text = text.replace(match.group(0), 'export_files=PackedStringArray(' + ', '.join('"' + f + '"' for f in files) + ')\n')
    preset.write_text(text)
    (ROOT / 'web/export-assets.json').write_text(json.dumps([f[6:] for f in files if f.startswith('res://assets/')], indent=2) + '\n')

def main():
    report = json.loads((ROOT / 'test-results/texture-scale/report.json').read_text())
    plan = build(report)
    RUNTIME.mkdir(parents=True, exist_ok=True)
    # Previous copies no longer in the plan are stale.
    for stale in RUNTIME.rglob('*.png'):
        if 'res://' + str(stale.relative_to(ROOT)) not in {v['runtime'] for v in plan.values()}:
            stale.unlink(); Path(str(stale) + '.import').unlink(missing_ok=True)
    update_exports(plan)
    (RUNTIME / 'manifest.json').write_text(json.dumps({'note': 'Generated by tools/build_runtime_textures.py from measured display scale; sources stay the art of record.', 'textures': plan}, indent=1) + '\n')
    before = sum(v['source'][0] * v['source'][1] * 4 for v in plan.values()) / 2**20
    after = sum(v['runtime_size'][0] * v['runtime_size'][1] * 4 for v in plan.values()) / 2**20
    print(json.dumps({'reduced': len(plan), 'rgba_mib_before': round(before, 1), 'rgba_mib_after': round(after, 1)}))

if __name__ == '__main__':
    main()
